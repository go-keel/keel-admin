package main

import (
	"flag"
	"os"
	"slices"
	"strings"
	"testing"

	"github.com/go-keel/keel-admin/internal/core/perm"
)

var updatePermCodes = flag.Bool("update-perm-codes", false, "write web/src/generated/perm-code.ts")

// permCodeFile is the frontend's union of permission codes. It is generated, not hand-copied: the backend declares
// codes in Go (registerPermissions), and the frontend's has/usePerm/route staticData take this type, so a mistyped
// or removed code fails tsc instead of silently hiding a button.
const permCodeFile = "../../web/src/generated/perm-code.ts"

// TestGeneratePermCodeTS writes permCodeFile from the same registration di.go runs. It only runs as a generator
// (`make perms`, which passes -update-perm-codes); `make check-generated` regenerates and compares it like every
// other generated file.
func TestGeneratePermCodeTS(t *testing.T) {
	if !*updatePermCodes {
		t.Skip("generator: run make perms")
	}
	perm.ResetForTest()
	defer perm.ResetForTest()
	registerAll()

	codes := make([]string, 0, len(perm.All()))
	for c := range perm.All() {
		codes = append(codes, string(c))
	}
	slices.Sort(codes)

	var b strings.Builder
	b.WriteString(`// Generated by TestGeneratePermCodeTS (cmd/admin/permcode_gen_test.go) from registerPermissions in
// cmd/admin/di.go. Do not edit. Regenerate: make perms
//
// Purpose: the frontend's permission checks (has, usePerm, route staticData.perm) take this type, so a mistyped or
// removed code fails tsc instead of silently hiding an element.

/** Every permission code the backend registers. */
export type PermCode =
`)
	b.WriteString("  | '" + strings.Join(codes, "'\n  | '") + "';\n")
	if err := os.WriteFile(permCodeFile, []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}
