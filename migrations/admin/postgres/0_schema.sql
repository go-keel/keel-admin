-- Complete schema of the admin database (PostgreSQL dialect): every sys_* table at its latest shape, matching
-- internal/core/sys/data/*_model.go. The MySQL version is ../mysql/0_schema.sql; a change goes into both, table by
-- table in the same order. Part of the kernel: following upstream overwrites this directory whole, and the ALTER an
-- existing admin database needs is in the matching UPGRADING.md entry (docs/admin/domain-model.md, "Schema").
-- No AutoMigrate in code. Run it against the database database.admin in config.yaml points to (business tables are in
-- migrations/business/, run against the business database; both are required):
--   psql -h 127.0.0.1 -U postgres -d <admin database> -v ON_ERROR_STOP=1 -f migrations/admin/postgres/0_schema.sql

-- Text columns compare ignoring case and accents, as MySQL's utf8mb4_0900_ai_ci does (docs/practices/database.md).
CREATE COLLATION IF NOT EXISTS ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

-- Department tree (framework master data, soft delete only). ancestors is the id path from the root to the parent
-- department (such as 0,1,5,), used to expand subtrees.
CREATE TABLE IF NOT EXISTS sys_dept (
    id         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT         NOT NULL DEFAULT 0,  -- 0 = top-level department
    ancestors  VARCHAR(1024)  COLLATE ci NOT NULL DEFAULT '',
    name       VARCHAR(64)    COLLATE ci NOT NULL,
    sort       INT            NOT NULL DEFAULT 0,
    status     SMALLINT       NOT NULL DEFAULT 1,  -- 1 enabled, 0 disabled
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ(3) NULL
);
CREATE INDEX IF NOT EXISTS sys_dept_idx_parent ON sys_dept (parent_id);
CREATE INDEX IF NOT EXISTS sys_dept_idx_deleted_at ON sys_dept (deleted_at);

-- Admin accounts (framework master data, soft delete only, no delete endpoint).
CREATE TABLE IF NOT EXISTS sys_user (
    id             BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(64)    COLLATE ci NOT NULL,
    password       VARCHAR(128)   COLLATE ci NOT NULL,
    nickname       VARCHAR(64)    COLLATE ci NOT NULL DEFAULT '',
    -- Contact details: optional, not unique, not used to log in (format validated in the contract, see
    -- api/keel_admin/v1/user.proto).
    email          VARCHAR(254)   COLLATE ci NOT NULL DEFAULT '',
    phone          VARCHAR(32)    COLLATE ci NOT NULL DEFAULT '',
    dept_id        BIGINT         NOT NULL,
    is_root        SMALLINT       NOT NULL DEFAULT 0,
    status         SMALLINT       NOT NULL DEFAULT 1,  -- 1 enabled, 0 disabled
    otp_secret_enc BYTEA          NULL,
    otp_bound      SMALLINT       NOT NULL DEFAULT 0,
    otp_bound_at   TIMESTAMPTZ(3) NULL,
    token_version  INT            NOT NULL DEFAULT 0,
    avatar         TEXT           COLLATE ci NULL,
    ip_whitelist   VARCHAR(512)   COLLATE ci NOT NULL DEFAULT '',
    -- Personal settings that follow the account (JSON of api.keel_admin.v1.UserSettings). A TEXT type rather than
    -- JSON, see docs/practices/database.md (types); read-modify-write takes a row lock in a transaction, with no JSON
    -- functions.
    settings       TEXT           COLLATE ci NULL,
    created_at     TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at     TIMESTAMPTZ(3) NULL,
    CONSTRAINT sys_user_uk_username UNIQUE (username)
);
CREATE INDEX IF NOT EXISTS sys_user_idx_dept ON sys_user (dept_id);
CREATE INDEX IF NOT EXISTS sys_user_idx_deleted_at ON sys_user (deleted_at);

-- Roles (framework master data, soft delete only; deleting revokes the grants, rows in link tables stay).
CREATE TABLE IF NOT EXISTS sys_role (
    id         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(64)    COLLATE ci NOT NULL,
    name       VARCHAR(64)    COLLATE ci NOT NULL,
    sensitive  SMALLINT       NOT NULL DEFAULT 0,  -- 1 = only root can assign
    force_otp  SMALLINT       NOT NULL DEFAULT 0,  -- 1 = holders must bind an authenticator
    status     SMALLINT       NOT NULL DEFAULT 1,  -- 1 enabled, 0 disabled (a disabled role grants nothing)
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ(3) NULL,
    CONSTRAINT sys_role_uk_code UNIQUE (code)
);
CREATE INDEX IF NOT EXISTS sys_role_idx_deleted_at ON sys_role (deleted_at);

-- Which roles a user has (link table, replaced as a whole when the user is edited).
CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS sys_user_role_idx_role ON sys_user_role (role_id);

-- Permission codes granted by a role (link table; the codes themselves are registered in code, not in the database).
CREATE TABLE IF NOT EXISTS sys_role_permission (
    role_id   BIGINT       NOT NULL,
    perm_code VARCHAR(128) COLLATE ci NOT NULL,
    PRIMARY KEY (role_id, perm_code)
);
CREATE INDEX IF NOT EXISTS sys_role_permission_idx_perm ON sys_role_permission (perm_code);

-- A role's data scope policy per resource type: one row per role × resource type; scope_type is the scope type code.
CREATE TABLE IF NOT EXISTS sys_role_data_scope (
    id            BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       BIGINT         NOT NULL,
    resource_type VARCHAR(64)    COLLATE ci NOT NULL,
    scope_type    VARCHAR(32)    COLLATE ci NOT NULL,
    created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT sys_role_data_scope_uk_role_res UNIQUE (role_id, resource_type)
);
CREATE INDEX IF NOT EXISTS sys_role_data_scope_idx_res ON sys_role_data_scope (resource_type);

-- Management boundary: holders of role_id may assign assignable_role_id to others.
CREATE TABLE IF NOT EXISTS sys_role_assignable (
    role_id            BIGINT NOT NULL,
    assignable_role_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, assignable_role_id)
);
CREATE INDEX IF NOT EXISTS sys_role_assignable_idx_assignable ON sys_role_assignable (assignable_role_id);

-- Management boundary: departments a role may manage (expanded to the whole subtree when checked).
CREATE TABLE IF NOT EXISTS sys_role_manage_dept (
    role_id BIGINT NOT NULL,
    dept_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, dept_id)
);
CREATE INDEX IF NOT EXISTS sys_role_manage_dept_idx_dept ON sys_role_manage_dept (dept_id);

-- Explicit-assignment (RESOURCE_GRANT) instance rows: role × resource type × instance id.
-- Replaced as a whole in the same transaction as the policy rows of sys_role_data_scope (RoleRepo.Save).
-- The kernel does not interpret what an instance is (category, brand group, store); the option list comes from the
-- ListGrantable callback declared when the resource is registered. Like every sys_* table, only the kernel reads and
-- writes this one; after the business deletes an instance it requests cleanup through the perm.GrantRevoker port.
CREATE TABLE IF NOT EXISTS sys_role_resource_grant (
    role_id       BIGINT         NOT NULL,
    resource_type VARCHAR(64)    COLLATE ci NOT NULL,
    resource_id   BIGINT         NOT NULL,
    created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, resource_type, resource_id)
);
CREATE INDEX IF NOT EXISTS sys_role_resource_grant_idx_res_instance ON sys_role_resource_grant (resource_type, resource_id);

-- Audit log of write operations (append only, no delete).
CREATE TABLE IF NOT EXISTS sys_audit_log (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id     BIGINT         NOT NULL,
    action          VARCHAR(64)    COLLATE ci NOT NULL,
    target_type     VARCHAR(32)    COLLATE ci NOT NULL,
    target_id       VARCHAR(64)    COLLATE ci NOT NULL,
    -- The request body, with sensitive fields erased per the proto's (keel.v1.redact).sensitive.
    -- No before/after snapshots of the data: only business code knows their shape, so the framework can neither
    -- redact them nor guarantee completeness; trade-off in the package comment of internal/core/audit.
    request_payload TEXT           COLLATE ci NULL,
    reason          VARCHAR(255)   COLLATE ci NOT NULL DEFAULT '',
    ip              VARCHAR(45)    COLLATE ci NOT NULL DEFAULT '',
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS sys_audit_log_idx_operator ON sys_audit_log (operator_id, created_at);
CREATE INDEX IF NOT EXISTS sys_audit_log_idx_action ON sys_audit_log (action, created_at);
CREATE INDEX IF NOT EXISTS sys_audit_log_idx_target ON sys_audit_log (target_type, target_id);

-- Login log (append only, no delete).
CREATE TABLE IF NOT EXISTS sys_login_log (
    id         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT         NOT NULL DEFAULT 0,  -- 0 = username does not exist
    username   VARCHAR(64)    COLLATE ci NOT NULL DEFAULT '',
    status     SMALLINT       NOT NULL,            -- 1 success, 0 failure
    ip         VARCHAR(45)    COLLATE ci NOT NULL DEFAULT '',
    msg        VARCHAR(255)   COLLATE ci NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS sys_login_log_idx_user ON sys_login_log (user_id, created_at);

