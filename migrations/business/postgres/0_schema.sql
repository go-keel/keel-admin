-- Complete schema of the business database (PostgreSQL dialect), separate from the sys_* tables of the admin database
-- (see migrations/admin/): this file runs against the business database that database.default in config.yaml points
-- to; both databases are required. The MySQL version is ../mysql/0_schema.sql; a change goes into both. Directories,
-- baseline and incremental scripts: docs/guides/domain-model.md, "Schema".
--   psql -h 127.0.0.1 -U postgres -d <business database> -v ON_ERROR_STOP=1 -f migrations/business/postgres/0_schema.sql
-- Data scope filtering (permdata.ApplyScope) applies only to the business tables' own owner columns, with no
-- cross-database JOIN, so two databases and one (both sources set to the same DSN) behave the same.

-- Text columns compare ignoring case and accents, as MySQL's utf8mb4_0900_ai_ci does (docs/practices/database.md).
CREATE COLLATION IF NOT EXISTS ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

-- Example: delete after forking (up to the end of this table's last CREATE INDEX)
-- notice: notices, the example business module (internal/biz|data|service, business area). owner_user_id /
-- owner_dept_id are permdata.ApplyScope's default owner columns (contrast a non-default column mapping such as
-- created_by/dept_id, which needs an explicit remap with permdata.ApplyScopeWith).
-- category_id links to a category: category grants (explicit assignment, sys_role_resource_grant) gate notice
-- visibility through it (ApplyScopeWith(catSpec, Cols{PK: "category_id"})).
CREATE TABLE IF NOT EXISTS notice (
    id            BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(128)   COLLATE ci NOT NULL,
    content       TEXT           COLLATE ci NOT NULL,
    category_id   BIGINT         NOT NULL,
    owner_user_id BIGINT         NOT NULL,
    owner_dept_id BIGINT         NOT NULL,
    created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS notice_idx_category_id ON notice (category_id);
CREATE INDEX IF NOT EXISTS notice_idx_owner_user_id ON notice (owner_user_id);
CREATE INDEX IF NOT EXISTS notice_idx_owner_dept_id ON notice (owner_dept_id);

-- Example: delete after forking (up to the end of this CREATE TABLE)
-- notice_category: notice categories, the example of a grantable instance of explicit assignment (RESOURCE_GRANT).
-- No owner columns: categories are not isolated by user or department; visibility is decided by the role's category
-- grants (the instance grant rows are in sys_role_resource_grant on the kernel side; this table is only the business
-- entity). Names are unique: categories are options of a multi-select in role configuration, and equal names could
-- not be told apart.
CREATE TABLE IF NOT EXISTS notice_category (
    id         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(64)    COLLATE ci NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notice_category_uk_name UNIQUE (name)
);
