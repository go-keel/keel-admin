// Shared file: carried verbatim; never localized outside its source repository.
// Checked by scripts/check-cross-repo-sync.sh (as norm: the module path and proto package segment that make rename
// replaces are excepted); see docs/upgrading-protocol.md.
// Generates the frontend's reason union type from api/keel_admin/v1/error_reason.proto.
//
// Why generate: if the frontend's error routing (SESSION_KILLED in web/src/lib/api.ts) hard-coded strings, a backend
// rename or removal of a reason would give the frontend no signal; it would silently take the wrong branch (such as
// redirecting to login where it should show a toast). Generated, these sets are constrained by the ErrorReason union
// type, so a typo or a removed reason fails in tsc.
//
// Called by make proto and regenerated together with the pb files.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const PROTO = 'api/keel_admin/v1/error_reason.proto';
const OUT = 'web/src/generated/error-reason.ts';

const src = readFileSync(PROTO, 'utf8');

// Take only the "NAME = n" lines inside the enum ErrorReason block
const block = src.match(/enum\s+ErrorReason\s*\{([\s\S]*?)\n\}/);
if (!block) {
  console.error(`gen-error-reason: no enum ErrorReason found in ${PROTO}`);
  process.exit(1);
}
const names = [...block[1].matchAll(/^\s*([A-Z][A-Z0-9_]*)\s*=\s*\d+/gm)].map(
  (m) => m[1],
);
if (names.length === 0) {
  console.error('gen-error-reason: no reason parsed; refusing to generate an empty file');
  process.exit(1);
}

// Middleware reasons: they are not in the business proto, yet reach the frontend just the same. A hand-written list
// is bound to miss some: the first version missed VALIDATOR (buf.validate, the 400 for an empty username/password)
// and UNAUTHENTICATED (authz finds no principal), which should also count as session expiry. So they are scanned from
// the source.
//
// Scanned: the admin's own middleware (internal/core/middleware) and the middleware of Keel and kratos (module
// cache). It matches one construction form: errors.<Kind>("REASON", ...).
function scanReasons() {
  const roots = ['internal/core/middleware'];
  try {
    // Take the directory of the version go.mod pins, not the last one in the module cache: when another project has
    // installed a newer Keel, the latter makes the same commit generate different output on different machines, and
    // make check-generated reports falsely.
    // GOWORK=off: go.work would point Keel at local source, which derived repos do not have. Passed through env rather
    // than as a command prefix: on Windows execSync goes through cmd.exe, which understands neither `VAR=x cmd` nor
    // single quotes.
    const modDir = (mod) =>
      execFileSync('go', ['list', '-m', '-f', '{{.Dir}}', mod], {
        encoding: 'utf8',
        env: { ...process.env, GOWORK: 'off' },
      }).trim();
    const keel = `${modDir('github.com/go-keel/keel')}/middleware`;
    const kratos = `${modDir('github.com/go-kratos/kratos/v3')}/middleware`;
    roots.push(keel, kratos);
  } catch {
    console.warn('gen-error-reason: could not locate the module cache; scanning only the admin middleware');
  }
  // Walk with Node itself rather than calling grep: Windows has no /bin/bash, and a failed call would quietly scan
  // an empty set.
  const ctor =
    /errors\.(Unauthorized|Forbidden|BadRequest|InternalServer|New)\([^)]*"[A-Z_]{3,}"/g;
  const out = new Set();
  for (const root of roots) {
    let files = [];
    try {
      files = readdirSync(root, { recursive: true }).filter((f) => f.endsWith('.go'));
    } catch {
      continue;
    }
    for (const f of files) {
      const text = readFileSync(join(root, f), 'utf8');
      for (const hit of text.matchAll(ctor)) {
        for (const m of hit[0].matchAll(/"([A-Z][A-Z0-9_]{2,})"/g)) out.add(m[1]);
      }
    }
  }
  return [...out].sort();
}

const scanned = scanReasons().filter((n) => !names.includes(n));
// Sentinels: these must be found, one each from the admin's own authz, kratos's validate and Keel's auth. Missing any
// means the scan is broken (a path changed, the construction form changed, the module cache is not there); then
// make proto fails rather than producing an incomplete type, which would make the frontend treat uncovered reasons
// as "nonexistent" and silently take the wrong branch.
const SENTINELS = ['UNAUTHENTICATED', 'VALIDATOR', 'UNAUTHORIZED'];
const missing = SENTINELS.filter((n) => !scanned.includes(n));
if (missing.length > 0) {
  console.error(
    `gen-error-reason: the middleware scan missed ${missing.join(', ')}; the scan is broken, refusing to generate an incomplete type`,
  );
  process.exit(1);
}
const FRAMEWORK = scanned.map((n) => [n, 'middleware']);

const out = `// Generated by scripts/gen-error-reason.mjs from ${PROTO}. Do not edit.
// Regenerate: make proto
//
// Purpose: constrains the frontend's error routing sets (see src/lib/api.ts). If the backend removes or renames a
// reason and the frontend still references the old name, tsc fails at once instead of silently taking the wrong branch.

/** The ErrorReason enum of ${PROTO}. */
export type ProtoErrorReason =
${names.map((n) => `  | '${n}'`).join('\n')};

/** Reasons returned by middleware, not in the business proto (found by scanning the source). */
export type FrameworkErrorReason =
${FRAMEWORK.map(([n]) => `  | '${n}'`).join('\n')};

/** Every reason the frontend may receive. */
export type ErrorReason = ProtoErrorReason | FrameworkErrorReason;
`;

writeFileSync(OUT, out);
console.log(
  `✓ ${OUT} (${names.length} proto + ${FRAMEWORK.length} framework reasons)`,
);
