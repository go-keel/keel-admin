import createClient, { type Middleware } from 'openapi-fetch';
import { toast } from 'sonner';
import type { ErrorReason } from '@/generated/error-reason';
import type { paths } from '@/generated/openapi';
import { getLocale } from './locale';
import { getPreview } from './preview';

/**
 * Error-handling convention for endpoints (the keel / kratos standard response).
 *
 * Response body: HTTP non-2xx, body = { code, reason, message }. The server localizes message by Accept-Language (see
 * internal/i18n), so show it as is: the frontend must not keep a second copy of the text for each reason.
 *
 * There are only two rules:
 *   1. SESSION_KILLED (exactly 3 reasons) → ask the server to clear the cookie + go to the login page
 *   2. every other non-2xx → toast body.message
 *
 * There is no third class of "left to the caller, no global message". Such a class relies on "the caller will surely
 * handle it", and once a caller forgets, the error is silently swallowed: the hardest kind of failure to trace. The
 * default always speaks up; a page's extra handling (an OTP prompt, clearing a form, a redirect) adds to the toast and
 * does not replace it. The only cost is that cases like step-up show a toast and a dialog together, so the dialog
 * does not repeat the error text.
 */
export type ErrorBody = {
  code?: number;
  reason?: string;
  message?: string;
};

/** The error unwrap throws. A caller that needs to branch catches it and reads reason; the toast was already shown. */
export class ApiError extends Error {
  readonly reason: ErrorReason | '';
  readonly status: number;
  readonly body: ErrorBody | undefined;

  constructor(body: ErrorBody | undefined, status: number) {
    super(body?.message || `HTTP ${status}`);
    this.name = 'ApiError';
    this.reason = (body?.reason ?? '') as ErrorReason | '';
    this.status = status;
    this.body = body;
  }
}

/**
 * The only class that redirects to the login page automatically: the identity no longer holds. Deliberately exactly
 * three, all produced by framework / kernel middleware; a business reason must never be added here.
 *
 * Decide by reason, never by status === 401: 401 also covers an unfinished login flow
 * (INVALID_CREDENTIAL / CAPTCHA_INVALID) and step-up challenges (OTP_STEPUP and the like); deciding by status code
 * would turn "wrong code entered" into "logged out". This is not a design flaw: 401 for a failed login is the
 * correct use per RFC 7235, and it naturally shares the code with session expiry. HTTP cannot express the
 * difference, which is why reason is the contract and status only derived information.
 *
 * The type is constrained by ErrorReason (generated by make proto): if the backend renames or removes one, this fails
 * to compile at once.
 */
const SESSION_KILLED: ReadonlySet<ErrorReason> = new Set<ErrorReason>([
  'UNAUTHORIZED', // Keel auth: token missing / invalid / expired
  'UNAUTHENTICATED', // authz: no principal
  'SESSION_EXPIRED', // token_version bumped (password change / disabled / kicked out)
]);

/** Whether this error means "the identity no longer holds" (one of the three session-killing reasons). */
export function isSessionKilled(error: unknown): boolean {
  return (
    error instanceof ApiError && SESSION_KILLED.has(error.reason as ErrorReason)
  );
}

export type ErrorAction =
  | { kind: 'login' }
  | { kind: 'toast'; text: string }
  | { kind: 'none' };

/** The two rules as a pure function; performErrorAction applies the effect, which keeps it unit-testable. */
export function dispatchError(
  body: ErrorBody | undefined,
  fallbackText?: string,
): ErrorAction {
  if (body?.reason && SESSION_KILLED.has(body.reason as ErrorReason)) {
    return { kind: 'login' };
  }
  const text = body?.message || fallbackText;
  return text ? { kind: 'toast', text } : { kind: 'none' };
}

/** Headers injected into every request. Authorization is not injected: the session token is in an httpOnly cookie,
 *  which the browser sends automatically; the frontend cannot read it and does not need to. */
export function applyRequestHeaders(headers: Headers): void {
  // The language follows the frontend's choice, so backend error messages are localized to match
  headers.set('Accept-Language', getLocale());
  // Permission preview (root only): send the selected roles, and the backend reduces root to that role set's
  // permission view. The backend ignores this header from non-root users, so it opens no escalation path.
  const preview = getPreview();
  if (preview) headers.set('X-Preview-Roles', preview.ids);
}

/**
 * The only entry point for step-up: turns the OTP code into a piece of the request init, spread at the call site:
 * `api.POST(path, { body, ...stepUp(code) })`. Not global mutable state: two concurrent writes would mix up their
 * codes.
 */
export const stepUp = (otpCode: string) => ({
  headers: { 'X-OTP-Code': otpCode },
});

const LOGIN_PATH = '/login';

// Where to go when the session is killed. Defaults to a full-page redirect (works before the entry has started);
// once main.tsx is up it is replaced by a router navigation, saving a blank-screen reload.
let sessionKilled = (redirect: string): void => {
  window.location.replace(
    `${LOGIN_PATH}?redirect=${encodeURIComponent(redirect)}`,
  );
};

export const setSessionKilledHandler = (
  handler: (redirect: string) => void,
): void => {
  sessionKilled = handler;
};

function goLogin(): void {
  const { pathname, search } = window.location;
  if (pathname === LOGIN_PATH) return;
  sessionKilled(pathname + search);
}

export function performErrorAction(action: ErrorAction): void {
  if (action.kind === 'login') {
    // The cookie is httpOnly and the frontend cannot delete it: ask the server to clear it, otherwise the browser keeps
    // sending a dead ticket and every request ends in a wasted 401. Not through the client below: it would hit the
    // middleware again. An empty body is rejected with 400 (the RPC request is required), so send {} explicitly.
    // Do not wait for it: the redirect must not be held up by this step.
    void fetch('/v1/sys/auth/logout', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: '{}',
    }).catch(() => {});
    goLogin();
    return;
  }
  // The text itself is the toast ID: the same message arriving twice (page prefetch and component fetch both
  // failing) shows once.
  if (action.kind === 'toast') toast.error(action.text, { id: action.text });
}

async function readErrorBody(
  response: Response,
): Promise<ErrorBody | undefined> {
  try {
    return (await response.clone().json()) as ErrorBody;
  } catch {
    return undefined;
  }
}

const errorMiddleware: Middleware = {
  onRequest({ request }) {
    applyRequestHeaders(request.headers);
    return request;
  },
  async onResponse({ response }) {
    if (response.ok) return;
    performErrorAction(
      dispatchError(await readErrorBody(response), response.statusText),
    );
  },
  onError({ error }) {
    // Network down / timeout: the server never answered, fall back to the browser's wording.
    toast.error(error instanceof Error ? error.message : String(error));
  },
};

export const api = createClient<paths>({ baseUrl: '/' });
api.use(errorMiddleware);

/**
 * openapi-fetch returns { data, error }, while TanStack Query expects a throw. This layer flips it; the middleware has
 * already shown the toast, this only gives the caller an error it can branch on.
 */
export function unwrap<T>(result: {
  data?: T;
  error?: unknown;
  response: Response;
}): T {
  if (result.error !== undefined) {
    throw new ApiError(result.error as ErrorBody, result.response.status);
  }
  return result.data as T;
}
