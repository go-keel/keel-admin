import { createFileRoute, useRouter } from '@tanstack/react-router';
import { useMemo, useState } from 'react';
import { Controller } from 'react-hook-form';
import { useTranslation } from 'react-i18next';
import { z } from 'zod';
import { FormDialog } from '@/components/containers';
import {
  DataTable,
  type DataTableColumn,
  RowActions,
} from '@/components/data-table';
import { DateTimeText } from '@/components/fields';
import { PageHeader } from '@/components/page-header';
import { Button } from '@/components/ui/button';
import { Field, FieldError, FieldLabel } from '@/components/ui/field';
import { Input } from '@/components/ui/input';
import { useList } from '@/hooks/use-list';
import { useZodForm } from '@/lib/form';
import { widthFor } from '@/lib/table';
import {
  createCategory,
  deleteCategory,
  type NoticeCategoryListItem,
  noticeCategoryList,
} from './-api';

/**
 * Category management page. A page rather than a drawer inside notice management: it is a paged list, and a drawer
 * holds only a one-screen summary (container rules in AGENTS.md). "Manage categories" depends on "View notices", so
 * having it opens notice management.
 */
export const Route = createFileRoute('/_app/notices/categories')({
  staticData: {
    titleKey: 'app:notices.categories',
    perm: 'ops:notice:category',
  },
  // No filters, so the URL carries no parameters; entering always lands on page 1.
  ...noticeCategoryList.route,
  component: CategoriesPage,
});

function CategoriesPage() {
  const { t } = useTranslation('app');
  const list = useList(noticeCategoryList, Route);
  // Reaching this page means holding "Manage categories", and creating a category uses the same code; no check needed.
  const [creating, setCreating] = useState(false);

  const columns = useCategoryColumns();

  return (
    <>
      <PageHeader
        actions={
          <Button onClick={() => setCreating(true)}>
            {t('notices.createCategory')}
          </Button>
        }
      />
      {/* No filters, so no FilterBar: a list definition with empty fields still provides the result set and loader
          prefetch. */}
      <DataTable<NoticeCategoryListItem>
        tableKey="notices.categories"
        columns={columns}
        pinning={{ start: ['id'], end: ['actions'] }}
        {...list.table}
      />
      <CategoryForm open={creating} onClose={() => setCreating(false)} />
    </>
  );
}

function useCategoryColumns(): DataTableColumn<NoticeCategoryListItem>[] {
  const { t, i18n } = useTranslation('app');
  const { t: tSys } = useTranslation();
  const router = useRouter();
  return useMemo(
    () => [
      { id: 'id', accessorKey: 'id', header: 'ID', size: 90 },
      {
        id: 'name',
        accessorKey: 'name',
        header: t('notices.category'),
        size: 240,
      },
      {
        id: 'createdAt',
        header: tSys('table.createdAt'),
        size: 220,
        cell: ({ row }) => <DateTimeText value={row.original.createdAt} />,
      },
      {
        id: 'actions',
        header: tSys('table.actions'),
        // Measured content width (buttons + padding + 8px margin): English 254px, Chinese 163px, Japanese 201px; the
        // longest set is "View announcements ↗ + Delete"
        size: widthFor(
          { default: 254, 'zh-CN': 163, 'ja-JP': 201 },
          i18n.language,
        ),
        cell: ({ row }) => (
          <RowActions
            actions={[
              // Related list: jump to notice management filtered by this row's category, opened in a new browser tab,
              // so the browsing position in this category list is not lost (a live example of rule 6 of the container
              // split). Generated by the router from notice management's definition; a wrong key fails to compile, so
              // do not hand-build it.
              {
                kind: 'button',
                key: 'notices',
                label: t('notices.viewNotices'),
                href: router.buildLocation({
                  to: '/notices',
                  search: { categoryId: row.original.id ?? '' },
                }).href,
              },
              {
                kind: 'button',
                key: 'delete',
                label: tSys('action.delete'),
                tone: 'destructive',
                // A button exposed on the row confirms with a popover next to it (container rules), as in notice
                // management.
                confirm: {
                  title: t('notices.deleteCategory'),
                  description: t('notices.deleteCategoryHint', {
                    name: row.original.name ?? '',
                  }),
                  onConfirm: () => deleteCategory(row.original.id ?? ''),
                },
              },
            ]}
          />
        ),
      },
    ],
    [t, tSys, router, i18n.language],
  );
}

/** Matches the constraints of the server's CreateNoticeCategoryRequest; the server is still the last gate. */
const categorySchema = z.object({ name: z.string().trim().min(1).max(64) });

function CategoryForm({
  open,
  onClose,
}: {
  open: boolean;
  onClose: () => void;
}) {
  const { t } = useTranslation('app');
  const form = useZodForm(categorySchema, {
    open,
    defaultValues: { name: '' },
  });

  return (
    <FormDialog
      open={open}
      onClose={onClose}
      title={t('notices.createCategory')}
      form={form}
      onSubmit={(v) => createCategory(v.name)}
    >
      <Controller
        name="name"
        control={form.control}
        render={({ field, fieldState }) => (
          <Field data-invalid={fieldState.invalid}>
            <FieldLabel htmlFor="category-name">
              {t('notices.category')}
            </FieldLabel>
            <Input
              {...field}
              id="category-name"
              aria-required
              aria-invalid={fieldState.invalid}
            />
            {fieldState.invalid ? (
              <FieldError errors={[fieldState.error]} />
            ) : null}
          </Field>
        )}
      />
    </FormDialog>
  );
}
